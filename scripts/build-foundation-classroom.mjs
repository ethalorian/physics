import fs from 'node:fs';
import vm from 'node:vm';

const root = 'public/foundations/unit-1';
const context = {window:{}};
vm.runInNewContext(fs.readFileSync(root+'/lesson-openings.js','utf8'), context);
vm.runInNewContext(fs.readFileSync(root+'/worksheet-questions.js','utf8'), context);
const catalog = {};
for (let day=1; day<=22; day++) for (const track of ['cpa','honors']) {
  const lesson=context.window.foundationOpeningLessons[day];
  const questions=context.window.foundationWorksheetQuestions[day][track];
  const slides=[
    {id:'opening',label:'Learning target · choose one opening',section:-1,notes:'Read the target and success criteria. Choose Draw along, Show what happens, or Test a claim; use one opening.'},
    ...['draw','demo','claim'].map(mode=>({id:mode,label:lesson[mode].title,section:-1,opening:mode,notes:'Model this opening, then move to the individual check. Students add to their doodle page.'})),
    {id:'check',label:'Individual check · did we meet the target?',section:-1,opening:'check',notes:'Give students time to draw or explain before revealing the reasoning.'},
    {id:'A',label:'A · vocabulary / all four Frayer models',section:0,notes:'Choose the word students need. Complete selected boxes during practice; all four words have printed Frayer models.'},
    {id:'B',label:'B · doodle along',section:1,notes:'Model the marks students add to Section B. Ask what each mark means before showing your reasoning.'},
    {id:'C',label:'C · draw and color the note figure',section:2,notes:'Reveal one mark at a time and wait for student pencils. You can annotate the figure on the projector.'},
    {id:'D',label:'D · worked example',section:3,notes:'Reveal the rule, work, and answer one step at a time. Then move to a worksheet question.'},
    ...questions.map(q=>({id:'worksheet-'+q.number,label:'Worksheet #'+q.number+' · '+q.title,section:-2,question:q.number,notes:'Select Question + grid, Question only, or Grid only. Use the paper selector for squares, axes, dots, or blank paper. Students work in their binders.'})),
    {id:'E',label:'E · final meeting / team transfer',section:4,notes:'Save this for the final meeting. Teams choose a job, make their call, then respond to the incoming update.'},
  ];
  slides.forEach((s,i)=>{s.next=Math.min(i+1,slides.length-1);s.prev=Math.max(i-1,0)});
  for(const i of [1,2,3]){slides[i].next=4;slides[i].prev=0}
  slides[4].next=6;slides[6].prev=4;
  catalog[day+'-'+track]=slides;
}
const json=JSON.stringify(catalog,null,2)+'\n';
fs.writeFileSync('src/data/foundation-classroom-scenes.json',json);
fs.writeFileSync(root+'/classroom-scenes.js','/* Generated by scripts/build-foundation-classroom.mjs */\nwindow.foundationClassroomScenes = '+json+';\n');
