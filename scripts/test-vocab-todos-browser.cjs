const assert = require('node:assert/strict')
const { chromium } = require('/Users/craigantocci/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const base = 'http://127.0.0.1:4337'
;(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' })
  try {
    const context = await browser.newContext({ viewport: { width: 1366, height: 900 }, reducedMotion: 'reduce' })
    const page = await context.newPage(), home = await context.newPage(), errors = []
    for (const tab of [page, home]) tab.on('pageerror', error => errors.push(error.message))
    const fixture = async query => (await page.request.get(`${base}/fixture?${query}`)).json()
    await fixture('reset')
    await home.goto(`${base}/home`)
    await home.getByText('0 of 1 done', { exact: true }).waitFor()
    await page.goto(base)
    await page.getByRole('heading', { name: 'Assignment in progress', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Start untimed recognition check', exact: true }).click()
    const answer = async () => {
      for (const word of ['Position', 'Displacement']) await page.locator('section').filter({ has: page.getByRole('heading', { name: new RegExp('Definition of ' + word + '$') }) }).getByRole('radio', { name: word, exact: true }).check()
    }
    await answer()
    await fixture('fail-save')
    await page.getByRole('button', { name: 'Submit check', exact: true }).click()
    await page.getByText('Check could not save. Please retry.', { exact: true }).waitFor()
    assert.equal(await page.getByRole('radio', { checked: true }).count(), 2)
    assert.equal((await fixture('')).vocab_checks.filter(c => c.completed_at).length, 0)
    await fixture('fail-progress')
    await page.getByRole('button', { name: 'Submit check', exact: true }).click()
    await page.getByRole('heading', { name: 'Check saved · 2/2 correct', exact: true }).waitFor()
    await page.getByText('Your check is saved, but assignment progress could not refresh.', { exact: false }).waitFor()
    assert.equal((await fixture('')).vocab_checks.filter(c => c.completed_at).length, 1)
    await page.getByRole('button', { name: 'Refresh progress', exact: true }).click()
    await page.getByText('1 check saved · 0 of 2 words at goal', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Start next check', exact: true }).click()
    await answer()
    await page.getByRole('button', { name: 'Submit check', exact: true }).click()
    await page.getByRole('heading', { name: 'Assignment complete', exact: true }).waitFor()
    await page.getByText('2 checks saved · 2 of 2 words at goal', { exact: true }).waitFor()
    await home.evaluate(() => window.dispatchEvent(new Event('focus')))
    await home.getByText('1 of 1 done', { exact: true }).waitFor()
    await fixture('stale')
    await home.evaluate(() => window.dispatchEvent(new Event('pageshow')))
    await home.getByText('Done', { exact: true }).waitFor()
    assert.equal(await home.getByText('Review due', { exact: true }).count(), 0)
    await page.screenshot({ path: '/private/tmp/vocab-todos-complete-desktop.png', fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: '/private/tmp/vocab-todos-complete-mobile.png', fullPage: true })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'student mobile overflow')
    await page.goto(`${base}/teacher`)
    await fixture('fail-archive')
    await page.getByRole('button', { name: 'Remove from student to-dos', exact: true }).click()
    await page.getByText('Could not update the assignment.', { exact: true }).waitFor()
    assert.equal((await fixture('')).vocab_tasks[0].active, true)
    await page.getByRole('button', { name: 'Remove from student to-dos', exact: true }).click()
    await page.getByRole('button', { name: 'Restore to student to-dos', exact: true }).waitFor()
    await home.evaluate(() => window.dispatchEvent(new Event('focus')))
    await home.getByText('0 of 0 done', { exact: true }).waitFor()
    await home.getByText('No vocabulary assigned.', { exact: true }).waitFor()
    assert.equal((await fixture('')).vocab_checks.filter(c => c.completed_at).length, 2)
    await page.screenshot({ path: '/private/tmp/vocab-todos-removed-mobile.png', fullPage: true })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'teacher mobile overflow')
    await page.getByRole('button', { name: 'Restore to student to-dos', exact: true }).click()
    await page.getByRole('button', { name: 'Remove from student to-dos', exact: true }).waitFor()
    await home.evaluate(() => window.dispatchEvent(new Event('focus')))
    await home.getByText('1 of 1 done', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Edit assignment', exact: true }).click()
    await page.getByRole('button', { name: '3 checks per word', exact: true }).click()
    await page.getByRole('button', { name: 'Save changes', exact: true }).click()
    await page.getByRole('button', { name: 'Edit assignment', exact: true }).waitFor()
    await home.evaluate(() => window.dispatchEvent(new Event('focus')))
    await home.getByText('0 of 1 done', { exact: true }).waitFor()
    await page.setViewportSize({ width: 1366, height: 900 })
    await page.screenshot({ path: '/private/tmp/vocab-todos-settings-desktop.png', fullPage: true })
    assert.deepEqual(errors, [])
    console.log('PASS: student save failure/retry, saved-result refresh failure/retry, remaining rounds, completion, Home focus/pageshow refresh, stale review stays done, archive failure/retry, removal/restore with evidence preserved, updated requirements, desktop/mobile layout; no page errors.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
