const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
const fs = require('node:fs');
const esbuild = require('esbuild');
const out = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'sei-publish-')), 'sei.cjs');
esbuild.buildSync({ entryPoints: [path.join(__dirname, '../src/lib/sei.ts')], outfile: out, bundle: true, platform: 'node' });
const { modesFor, seiLint } = require(out);
assert.deepEqual(modesFor({ modes: ['sketch'] }, 'bare'), ['text', 'sketch']);
const capture = { id: 'exit', type: 'exit_ticket', prompt: 'Explain the graph.', sei: { frames: [{ level: 2, text: 'The pattern is ___ because ___.' }], visualBlockId: 'visual' } };
const graph = { id: 'visual', type: 'graph', series: [{ label: 'Position', points: [[0, 0], [1, -1]] }] };
const errors = blocks => seiLint(blocks).filter(x => x.severity === 'error');
assert.equal(errors([graph, { id: 'reading', type: 'prose', markdown: 'Read.' }, capture]).length, 0);
assert.ok(errors([{ ...graph, visibilityTrack: 'honors' }, capture]).some(x => x.rule === 'visual'));
assert.equal(errors([{ ...graph, visibilityTrack: 'honors' }, { ...capture, visibilityTrack: 'honors' }]).length, 0);
assert.ok(errors([{ id: 'visual', type: 'sketch', instruction: 'Draw.' }, capture]).some(x => x.rule === 'visual'));
assert.equal(errors([{ id: 'visual', type: 'sketch', backgroundDiagram: { kind: 'free_body' } }, capture]).length, 0);
assert.ok(errors([{ ...capture, sei: { ...capture.sei, visualBlockId: 'missing' } }]).some(x => x.rule === 'visual'));
assert.equal(errors([{ ...capture, sei: { frames: capture.sei.frames, visual: { kind: 'free_body' } } }]).length, 0);
assert.ok(errors([{ id: 'rating', type: 'self_assessment', targetIds: ['t'] }]).some(x => x.rule === 'exit'));
console.log('PASS SEI response alternatives persist; real and track-compatible visual references; self-assessment requires final evidence');
