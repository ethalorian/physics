import { readFileSync, writeFileSync } from 'node:fs'
import { diagram, esc } from '../src/data/deck-sources/worksheet-guided/diagrams.mjs'
import { emphasizeMarkup } from '../src/lib/assignment-emphasis.mjs'

const source = new URL('../resources/worksheet-decks/', import.meta.url)
const read = name => JSON.parse(readFileSync(new URL(name, source), 'utf8'))
const visualKey = visual => JSON.stringify(visual, Object.keys(visual).sort())
const figures = new Map(read('figures.json').map(({visual, svg}) => [visualKey(visual), svg]))
const lessons = {}

function studentText(value) {
  return esc(emphasizeMarkup(value))
    .replace(/&lt;(\/?)(b|i|u|sub|sup)&gt;/g, '<$1$2>')
    .replace(/(?:&lt;br\s*\/?&gt;|\n+)/g, '<br>')
}

function worksheetQuestion({number, title, prompt, visual}) {
  const question = {number, title, prompt: studentText(prompt)}
  if (!visual) return question
  const html = ['graph', 'vector_grid', 'table'].includes(visual.kind)
    ? diagram(visual)
    : figures.get(visualKey(visual))
  if (!html) throw new Error('Missing worksheet figure for ' + title)
  return {...question, figure: html, caption: studentText(visual.caption || '')}
}

for (const day of read('source.json').filter(day => day.unit === 1)) {
  lessons[day.day] = {}
  for (const track of ['cpa', 'honors']) {
    const selection = day[track].filter(q => q.number >= 3 && q.number <= 6)
    if (selection.length !== 4) throw new Error('Missing worksheet questions for Day ' + day.day)
    lessons[day.day][track] = selection.map(worksheetQuestion)
  }
}

const output = new URL('../public/foundations/unit-1/worksheet-questions.js', import.meta.url)
writeFileSync(output, '/* Generated by scripts/build-foundation-worksheet-questions.mjs */\nwindow.foundationWorksheetQuestions = ' + JSON.stringify(lessons, null, 2).replace(/<\/script/gi,'<\\/script') + ';\n')
