/** Curriculum plan set a course contributes. A course's `program` wins over its
 *  (physics) `track`: trades classes read the trades plans, Project Physics (the
 *  MVP section) reads the four mission phases, everything else reads its track. */
export function trackForCourse(c: { track: string | null; program: string | null }): string | null {
  if (c.program === 'trades') return 'trades'
  if (c.program === 'projects') return 'projects'
  return c.track === 'honors' ? 'cpa' : c.track
}

/** Find a day's plan across the teacher's tracks (only `cpa` ships today). */
export function findDay(unitId: string, day: number, tracks: string[]): DayPlan | null {
  for (const t of tracks) {
    // Historical plans remain addressable for prior evidence; only the active
    // ETF projects appear in the teacher's current course list.
    const u = PLANS[t === 'honors' ? 'cpa' : t]?.[unitId]
      ?? (t === 'trades' ? (tradesResetPlans as Record<string, DayPlan[]>)[unitId] : undefined)
    if (!u) continue
    const hit = u.find((p) => p.day === day)
    if (hit) return hit
  }
  return null
}

function escapeHtml(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

export interface BuildOpts {
  /** When `true`, add @page CSS for PDF (page-break-inside on tables, etc.). */
  forPdf?: boolean
}

/** Wrap the authored bodyHtml in a styled envelope. Same look for docx + pdf;
 *  PDF adds a print stylesheet so the headless browser paginates well. */
export function buildLessonPlanHtml(unitId: string, day: DayPlan, opts: BuildOpts = {}): string {
  const unitName = UNIT_LABEL[unitId] ?? unitId
  const printCss = opts.forPdf
    ? `
      @page { size: Letter; margin: 1in; }
      table, tr, td, th { page-break-inside: avoid; }
      h1, h2 { page-break-after: avoid; }
    `
    : ''
  return `<!DOCTYPE html><html><head><meta charset="utf-8" /><style>
    body { font-family: 'Atkinson Hyperlegible', Calibri, sans-serif; font-size: 11pt; color: #111; }
    h1 { font-size: 18pt; margin: 0 0 4pt 0; }
    h2 { font-size: 13pt; text-transform: uppercase; letter-spacing: 0.04em; color: #444; margin: 14pt 0 4pt 0; }
    .meta { font-size: 10pt; color: #666; margin-bottom: 14pt; }
    table { border-collapse: collapse; width: 100%; margin: 8pt 0; }
    td, th { border: 0.75pt solid #999; padding: 6pt 8pt; vertical-align: top; }
    tr:first-child td > strong:first-child { color: #222; }
    p { margin: 4pt 0; line-height: 1.4; }
    ul, ol { margin: 4pt 0 4pt 18pt; }
    li { margin: 2pt 0; }
    strong { font-weight: 700; }
    em { color: #555; }
    ${printCss}
  </style></head><body>
    <h1>${escapeHtml(day.title)}</h1>
    <div class="meta">${escapeHtml(unitName)} &middot; Teacher lesson plan</div>
    ${day.bodyHtml}
  </body></html>`
}

/** Compute the list of curriculum tracks the requester is scoped to. Admins
 *  see all tracks; teachers see only the tracks they teach (from `courses`). */
export async function resolveTracks(opts: { role: string; scopeEmail: string; courseId?: string | null }): Promise<string[]> {
  const { supabaseAdmin } = await import('@/lib/supabase')
  if (opts.courseId) {
    const r = await supabaseAdmin.from('courses').select('track, program, teacher_email').eq('id', opts.courseId).maybeSingle()
    if (r.error) throw r.error
    if (!r.data || (opts.role === 'teacher' && r.data.teacher_email !== opts.scopeEmail)) return []
    const track = trackForCourse(r.data); return track ? [track] : []
  }
  if (opts.role === 'admin' || opts.role === 'observer') return Object.keys(PLANS)
  const { data, error } = await supabaseAdmin.from('courses').select('track, program').eq('teacher_email', opts.scopeEmail)
  if (error) throw error
  const rows = (data ?? []) as { track: string | null; program: string | null }[]
  return [...new Set(rows.map(trackForCourse).filter((t): t is string => Boolean(t)))]
}
